#!/usr/bin/env bash
# The egress proxy's start command: start, upgrade, or apply a config change (an added or
# removed caller network, or a policy edit). Idempotent: with the same image and config
# it changes nothing and restarts nothing.
#
# Two modes. Installed (~/.egress/start.sh, written by the installer): runs the image the
# active runtime set names (state/runtime/image, pinned by digest) and never builds or
# pulls. Checkout (./start.sh in this repo, development only): builds the image
# egress-proxy from the checkout and runs it.
#
# The config's sections are the only list of caller networks. Compose cannot read them, so
# this renders a compose override from them with the proxy image itself (`proxy
# compose`, which validates the config) and starts compose with it. The override lives in
# the config directory's state/, outside the checkout or runtime set, so another egress
# version renders the same networks.
#
# After the start it prints each caller network's rules in effect (`proxy rules`: the
# built-in floor, the start-time addresses and the config) and writes them to
# effective-policy.txt in the config directory, replaced at every start.
#
# Exit codes: 0 started; 2 no config, a config error (the error names the network and
# key) or, installed, the image not on this machine; 1 an existing network with the wrong
# internal or IPv6 setting; any other: the failing docker command's. On a config or
# network error the override and the running proxy are left as they were; an upgrade
# removes the old project's container before `up`, so a failing `up` leaves no proxy
# running.
set -euo pipefail

# This script's directory, symlinks not resolved: ~/.egress/start.sh is a symlink into
# ~/.egress/state/runtime, and ~/.egress is the install.
here=$(CDPATH='' cd -- "$(dirname "$0")" && pwd)

if [[ -f $here/state/runtime/image ]]; then
  config_dir=$here
  # Its values follow the generated-file header.
  image=$(sed '/^#/d' "$here/state/runtime/image")
  project=$here/state
  compose_file=$here/state/runtime/compose.yaml
  build=""
else
  config_dir=${EGRESS_CONFIG_DIR:-$HOME/.egress}
  image=egress-proxy
  project=$here
  compose_file=$here/compose.yaml
  build=yes
fi

if [[ ! -f $config_dir/config.local.yaml ]]; then
  echo "start.sh: $config_dir/config.local.yaml not found; copy config.example.yaml there (README.md)" >&2
  exit 2
fi
# Absolute: compose.yaml mounts this directory, and compose resolves a relative path
# against the project directory, not ours.
config_dir=$(CDPATH='' cd -- "$config_dir" && pwd)
export EGRESS_CONFIG_DIR=$config_dir EGRESS_IMAGE=$image
mkdir -p "$config_dir/state"
override=$config_dir/state/compose.networks.yaml

base=(docker compose --project-directory "$project" -f "$compose_file")

if [[ -n $build ]]; then
  docker build -t "$image" "$here"
elif ! docker image inspect "$image" >/dev/null 2>&1; then
  echo "start.sh: image $image is not on this machine; reinstall it (README.md)" >&2
  exit 2
fi

tmp=$(mktemp "$config_dir/state/.compose.networks.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
  echo "# $override: the caller networks' compose override, generated by start.sh from"
  echo "# config.local.yaml at every start; do not edit, the next start replaces it. To change"
  echo "# the caller networks or their policy, edit config.local.yaml, then run start.sh."
  docker run --rm --pull never --network none --read-only --cap-drop ALL \
    --security-opt no-new-privileges:true -v "$config_dir:/etc/egress:ro" \
    "$image" compose
} >"$tmp" || exit $?

# The networks are external to compose (compose.yaml, the override), so compose never
# checks which project created them: an install from before the rename keeps its
# networks and the callers on them, with no warning. Create the missing ones.
# ensure_network <name> <what> <format> <want> <create flags...>: an existing one must
# give <want> for the inspect <format> (<what> names it in the error).
ensure_network() {
  local name=$1 what=$2 format=$3 want=$4 got
  shift 4
  if got=$(docker network inspect --format "$format" "$name" 2>/dev/null); then
    if [[ $got != "$want" ]]; then
      echo "start.sh: network $name exists with $what $got, want $want; remove it (docker network rm $name)" >&2
      exit 1
    fi
  else
    docker network create "$@" "$name" >/dev/null
  fi
}
networks=$(sed -n 's/^    name: "\(egress-[^"]*\)"$/\1/p' "$tmp")
for net in $networks; do
  ensure_network "$net" internal '{{.Internal}}' true --internal
done
# IPv4 only, as compose.yaml says.
ensure_network egress-uplink 'internal and IPv6' '{{.Internal}} {{.EnableIPv6}}' 'false false' --ipv6=false

mv "$tmp" "$override"

# An install from before the rename to proxy runs as compose project egress, which this
# project does not manage: remove its container before this one starts, since two
# containers holding one alias would make the new one resolve the old one's address and
# exit. The caller networks stay.
old=$(docker ps -aq --filter label=com.docker.compose.project=egress --filter label=windroc.egress.contract)
if [[ -n $old ]]; then
  echo "start.sh: removing the proxy container of the old compose project egress" >&2
  # A read loop, not mapfile: the Mac's bash is 3.2.
  while read -r id; do
    docker rm -f "$id" >/dev/null
  done <<<"$old"
fi

"${base[@]}" -f "$override" up -d

# A policy edit within the sections changes no compose file, so compose keeps the running
# container: restart it when its running policy differs from the config (`proxy drift`
# exits 3). A container compose just created or started reads this config itself.
rc=0
"${base[@]}" -f "$override" exec -T proxy /proxy drift >/dev/null 2>&1 || rc=$?
if ((rc == 3)); then
  echo "start.sh: the running policy differs from the config; restarting the proxy" >&2
  "${base[@]}" -f "$override" restart proxy
fi

# The rules in effect (README.md › Policy), from the running proxy's start facts. A proxy
# that has not reported them within 30 s (it failed to start, is still starting, or runs
# a policy other than the config's) gets a rules file that says so; the exit code stays
# as above.
rules_file=$config_dir/effective-policy.txt
rules_tmp=$(mktemp "$config_dir/.effective-policy.txt.XXXXXX")
rules_err=$(mktemp "$config_dir/state/.rules.err.XXXXXX")
trap 'rm -f "$tmp" "$rules_tmp" "$rules_err"' EXIT
version=$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.version"}}' "$image" 2>/dev/null) ||
  version=""
[[ -n $version && $version != "<no value>" ]] || version="development build"
rules="" reported=""
for ((i = 0; i < 30; i++)); do
  ((i == 0)) || sleep 1
  if rules=$("${base[@]}" -f "$override" exec -T proxy /proxy rules 2>"$rules_err"); then
    reported=yes
    break
  fi
done
if [[ -z $reported ]]; then
  why=$(head -n 1 "$rules_err" | sed 's/^proxy: //')
  [[ -n $why ]] || why="the proxy is not running"
  echo "start.sh: the proxy did not report its rules within 30 s ($why); see docker logs egress-proxy" >&2
  rules="No rules reported within 30 s of this start: $why. See docker logs egress-proxy, then run start.sh again."
fi
{
  echo "# $rules_file: the rules in effect for each caller network."
  echo "# Generated by start.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) for egress-proxy $version (image $image);"
  echo "# do not edit it: the next start replaces it. To change the policy, edit"
  echo "# $config_dir/config.local.yaml, then run $here/start.sh."
  echo
  printf '%s\n' "$rules"
} >"$rules_tmp"
chmod 0644 "$rules_tmp"
mv -f "$rules_tmp" "$rules_file"
if [[ -n $reported ]]; then printf '%s\n' "$rules"; fi
echo "start.sh: the rules in effect are also in $rules_file"
