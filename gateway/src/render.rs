//! `gateway compose`: the compose override that attaches the gateway to each caller
//! network in the config and advertises it in the labels. Only start.sh runs it.

use std::fmt::Write as _;

use crate::cli::Opts;
use crate::config::{self, Config, listen_alias, network_name};

const HEADER: &str = "# Generated by start.sh from config.local.yaml, one caller network per section; do not edit.\n";

/// The override for the config's caller networks: compose keys are the network keys, so a
/// network compose created before keeps its compose label. Pure: the same config always
/// gives the same bytes, which keeps start.sh idempotent.
pub fn compose_override(config: &Config, port: u16) -> String {
    let keys: Vec<&str> = config.networks.keys().map(String::as_str).collect();
    let list = keys.join(",");
    let mut out = String::from(HEADER);
    out.push_str("services:\n  gateway:\n    environment:\n");
    let _ = writeln!(out, "      EGRESS_NETWORKS: \"{list}\"");
    out.push_str("    labels:\n");
    let _ = writeln!(out, "      windroc.egress.networks: \"{list}\"");
    for key in &keys {
        let _ = writeln!(
            out,
            "      windroc.egress.network.{key}.name: \"{}\"",
            network_name(key)
        );
        let _ = writeln!(
            out,
            "      windroc.egress.network.{key}.proxy: \"http://{}:{port}\"",
            listen_alias(key)
        );
    }
    out.push_str("    networks:\n");
    for key in &keys {
        let _ = writeln!(
            out,
            "      {key}:\n        aliases: [\"{}\"]",
            listen_alias(key)
        );
    }
    out.push_str("networks:\n");
    for key in &keys {
        let _ = writeln!(
            out,
            "  {key}:\n    name: \"{}\"\n    internal: true",
            network_name(key)
        );
    }
    out
}

/// Prints the override for the config at `opts.config`; returns 0, or 2 on a config error.
pub fn run(opts: &Opts) -> u8 {
    match config::load(&opts.config) {
        Ok(config) => {
            print!("{}", compose_override(&config, opts.port));
            0
        }
        Err(e) => {
            eprintln!("gateway: {e}");
            2
        }
    }
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;
    use crate::config::parse;

    const TWO: &str = "version: 1\nnetworks:\n  workers:\n    mode: denylist\n  mini-op:\n    mode: allowlist\n    allow: [example.com]\n";

    #[test]
    fn two_networks_override() {
        let config = parse(Path::new("/c.yaml"), TWO).unwrap();
        assert_eq!(
            compose_override(&config, 4750),
            r#"# Generated by start.sh from config.local.yaml, one caller network per section; do not edit.
services:
  gateway:
    environment:
      EGRESS_NETWORKS: "mini-op,workers"
    labels:
      windroc.egress.networks: "mini-op,workers"
      windroc.egress.network.mini-op.name: "egress-mini-op"
      windroc.egress.network.mini-op.proxy: "http://egress-proxy-mini-op:4750"
      windroc.egress.network.workers.name: "egress-workers"
      windroc.egress.network.workers.proxy: "http://egress-proxy-workers:4750"
    networks:
      mini-op:
        aliases: ["egress-proxy-mini-op"]
      workers:
        aliases: ["egress-proxy-workers"]
networks:
  mini-op:
    name: "egress-mini-op"
    internal: true
  workers:
    name: "egress-workers"
    internal: true
"#
        );
    }

    #[test]
    fn one_network_and_port() {
        let config = parse(
            Path::new("/c.yaml"),
            "version: 1\nnetworks:\n  workers:\n    mode: denylist\n",
        )
        .unwrap();
        let text = compose_override(&config, 8080);
        let yaml: serde_yaml::Value = serde_yaml::from_str(&text).unwrap();
        let gateway = &yaml["services"]["gateway"];
        assert_eq!(gateway["environment"]["EGRESS_NETWORKS"], "workers");
        assert_eq!(
            gateway["labels"]["windroc.egress.network.workers.proxy"],
            "http://egress-proxy-workers:8080"
        );
        assert_eq!(gateway["networks"].as_mapping().unwrap().len(), 1);
        assert_eq!(yaml["networks"]["workers"]["internal"], true);
    }
}
