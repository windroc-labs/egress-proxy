//! `gateway compose` as a process.

use std::fs;
use std::process::{Command, Output};

fn compose(config: &str) -> Output {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("config.local.yaml");
    fs::write(&path, config).unwrap();
    Command::new(env!("CARGO_BIN_EXE_gateway"))
        .arg("compose")
        .arg("--config")
        .arg(&path)
        .env_remove("EGRESS_NETWORKS")
        .output()
        .unwrap()
}

#[test]
fn prints_the_override() {
    let out = compose("version: 1\nnetworks:\n  workers:\n    mode: denylist\n");
    assert_eq!(out.status.code(), Some(0));
    let text = String::from_utf8_lossy(&out.stdout);
    assert!(text.starts_with("# Generated by start.sh"), "{text}");
    assert!(text.contains("EGRESS_NETWORKS: \"workers\""), "{text}");
    assert!(out.stderr.is_empty());
}

#[test]
fn config_error_exits_2() {
    let out = compose("version: 1\nnetworks:\n  mini-op:\n    allow: [example.com]\n");
    assert_eq!(out.status.code(), Some(2));
    assert!(out.stdout.is_empty());
    let err = String::from_utf8_lossy(&out.stderr);
    assert!(err.contains("network mini-op: missing key mode"), "{err}");
}
